/**
 * แปลงวันที่เป็นรูปแบบไทย
 */
function thaiDate(string $date): string {
    $months = ['','ม.ค.','ก.พ.','มี.ค.','เม.ย.','พ.ค.','มิ.ย.','ก.ค.','ส.ค.','ก.ย.','ต.ค.','พ.ย.','ธ.ค.'];
    [$y, $m, $d] = explode('-', $date);
    return (int)$d . ' ' . $months[(int)$m] . ' ' . ((int)$y + 543);
}

/**
 * ดึงสีสำหรับ BMI badge
 */
function getBMIColor(float $bmi): string {
    if ($bmi < 18.5) return '#3b82f6';
    elseif ($bmi <= 22.9) return '#16a34a';
    elseif ($bmi <= 24.9) return '#ca8a04';
    elseif ($bmi <= 29.9) return '#ea580c';
    else return '#dc2626';
}

/**
 * ดึงสถานะ BMI ให้สั้น
 */
function getBMIStatus(float $bmi): string {
    if ($bmi < 18.5) return 'ผอม';
    elseif ($bmi <= 22.9) return 'ปกติ';
    elseif ($bmi <= 24.9) return 'ท้วม';
    elseif ($bmi <= 29.9) return 'อ้วน';
    else return 'อ้วนมาก';
}
